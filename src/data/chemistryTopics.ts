const CUSTOM_QUESTIONS_STORAGE_KEY = 'kimya_donanmasi_custom_questions_v1';

export function loadCustomQuestions(): ChemistryQuestion[] {
  try {
    const raw = localStorage.getItem(CUSTOM_QUESTIONS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed;
  } catch {
    return [];
  }
}

export function saveCustomQuestions(questions: ChemistryQuestion[]): void {
  try {
    localStorage.setItem(CUSTOM_QUESTIONS_STORAGE_KEY, JSON.stringify(questions));
  } catch {
    // Ignore storage quota errors safely
  }
}

export function getTopicById(topicId: ChemistryTopicId): ChemistryTopic {
  return CHEMISTRY_TOPICS.find((t) => t.id === topicId) ?? CHEMISTRY_TOPICS[0];
}
